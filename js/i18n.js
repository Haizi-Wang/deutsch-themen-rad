const tables = { de, zh };

export function getLang() {
  return localStorage.getItem(KEY) === "zh" ? "zh" : "de";
}

export function toggleLang() {
  const next = getLang() === "zh" ? "de" : "zh";
  localStorage.setItem(KEY, next);
  return next;
}

export function t(key, vars = {}) {
  const table = tables[getLang()] || de;
  let s = table[key] ?? de[key] ?? key;
  return String(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? "" : String(vars[k])));
}

export function applyChrome() {
  const lang = getLang();
  document.documentElement.lang = lang === "zh" ? "zh-Hans" : "de";
  document.title = t("docTitle");
  const name = document.getElementById("appName");
  const tag = document.getElementById("tagline");
  const btn = document.getElementById("langBtn");
  const nav = document.querySelector(".nav");
  if (name) name.textContent = t("appName");
  if (tag) tag.textContent = t("tagline");
  if (btn) btn.textContent = t("langBtn");
  if (nav) nav.setAttribute("aria-label", t("navAria"));
  const map = {
    plan: "navPlan",
    heute: "navHeute",
    sprechen: "navSprechen",
    pruefung: "navPruefung",
    feinschliff: "navFeinschliff",
    hoeren: "navHoeren",
    zeitung: "navZeitung",
    zuege: "navZuege",
    einstellungen: "navSetup",
  };
  document.querySelectorAll(".nav a[data-route]").forEach((a) => {
    const k = map[a.dataset.route];
    if (k) a.textContent = t(k);
  });
}
